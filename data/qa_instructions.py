def pick_instruction(category: str) -> str:
    if category == "not_found":
        # pick any style randomly — model must infer not_found from docs
        style = random.choice(["default", "detail", "short"])
    else:
        style = category
    
    return random.choice(INSTRUCTIONS[style])





